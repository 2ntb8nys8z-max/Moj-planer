import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const html=fs.readFileSync('index.html','utf8');
const code=html.slice(html.indexOf('let photoNoteSaving=false;'),html.indexOf('async function addEntryPhoto(input)'));
const nodes={photoNoteStatus:{},createPhotoNote:{},photoNoteLocation:{checked:false}};
let entries=[],blobs=new Map(),fail=false,opened;
const context=vm.createContext({navigator:{},crypto:{randomUUID:()=> 'photo-id'},Date,$:id=>nodes[id],saveVoiceMemo:async(id,file)=>blobs.set(id,file),deleteVoiceMemo:async id=>blobs.delete(id),addIdea:entry=>{if(fail)throw Error('QuotaExceededError');entries.push(entry);return entry},showView:()=>{},openIdeaActions:e=>opened=e});
vm.runInContext(code,context);
const run=file=>context.createPhotoNote({files:file?[file]:[],value:'chosen'});
await run();assert.equal(entries.length,0);
await run({type:'audio/mp4',size:10});assert.equal(entries.length,0);
await run({type:'image/jpeg',size:16*1024*1024});assert.equal(entries.length,0);
const file={type:'image/jpeg',size:123,name:'aparat.jpg'};
await run(file);assert.equal(entries.length,1);assert.equal(opened,entries[0]);assert.match(opened.title,/^Zdjęcie — /);assert.equal(opened.attachments[0].id,'photo-id');assert.equal(blobs.get('photo-id'),file);assert.equal(opened.creationLocation,undefined);
entries=[];blobs.clear();fail=true;await run(file);assert.equal(entries.length,0);assert.equal(blobs.size,0);assert.match(nodes.photoNoteStatus.textContent,/QuotaExceededError/);assert.equal(nodes.createPhotoNote.disabled,false);
fail=false;nodes.photoNoteLocation.checked=true;await run(file);assert.equal(entries.length,1);assert.match(nodes.photoNoteStatus.textContent,/bez lokalizacji/);
assert.match(html,/id="photoNoteInput"[^>]*capture="environment"/);
console.log('Photo note: cancellation, validation, attachment, rollback and unavailable location passed');
